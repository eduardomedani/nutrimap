create or replace function public.contas_fora_da_organizacao()
returns table (
  user_id uuid, email text, nome text,
  criada_em timestamptz, ultimo_login timestamptz,
  e_admin boolean, pacientes integer
)
language sql
stable
security definer
set search_path = public
as $fn$
  select
    n.id, u.email, n.nome, u.created_at, u.last_sign_in_at,
    exists (select 1 from public.admins a where a.user_id = n.id),
    (select count(*)::int from public.pacientes p where p.nutri_id = n.id)
  from public.nutricionistas n
  join auth.users u on u.id = n.id
  where not exists (select 1 from public.organizacao_usuarios ou where ou.auth_user_id = n.id)
    and public.tem_permissao('usuarios.gerenciar')
  order by u.last_sign_in_at desc nulls last;
$fn$;


-- O detalhe do §23. Conta modulo a modulo: zero num modulo NAO significa zero
-- nos outros, e a decisao sobre a conta depende de saber onde ha dado.
--
-- AS TABELAS SAO DESCOBERTAS, NAO ESCRITAS A MAO.
--
-- A primeira versao listava as tabelas numa sequencia de `union all`, e ela
-- nao passou nem da primeira aplicacao: `public.checkin_ocorrencias` esta
-- versionada em db/checkin_schema.sql mas NAO existe no banco, e uma
-- referencia estatica a tabela inexistente derruba a funcao inteira no parse —
-- levando junto as outras quinze contagens, que estavam certas.
--
-- Aqui a lista sai de information_schema e a contagem e dinamica. Efeitos:
--   * tabela ausente simplesmente nao aparece, em vez de quebrar tudo;
--   * modulo novo entra sozinho, sem editar esta funcao;
--   * o que ha de dado e o que o banco TEM, nao o que o repositorio espera.
--
-- O format(%I) cita o identificador e o valor vai por `using`, entao nao ha
-- superficie de injecao — os nomes vem do catalogo, nao de quem chama.
create or replace function public.conta_externa_detalhe(p_user_id uuid)
returns table (grupo text, item text, valor text)
language plpgsql
stable
security definer
set search_path = public
as $fn$
declare
  r         record;
  v_qtd     bigint;
  v_tabelas integer := 0;
  v_com     integer := 0;
begin
  -- Tres portas, e todas fecham em silencio: quem nao pode gerenciar usuarios
  -- nao descobre nem que a conta existe.
  if not public.tem_permissao('usuarios.gerenciar') then return; end if;
  if not exists (select 1 from public.nutricionistas n where n.id = p_user_id) then return; end if;
  if exists (select 1 from public.organizacao_usuarios ou where ou.auth_user_id = p_user_id) then return; end if;

  return query
    select 'CONTA'::text, 'e-mail'::text, u.email::text
      from auth.users u where u.id = p_user_id;
  return query
    select 'CONTA'::text, 'nome'::text, coalesce(n.nome, '(sem nome)')::text
      from public.nutricionistas n where n.id = p_user_id;
  return query
    select 'CONTA'::text, 'criada em'::text, u.created_at::date::text
      from auth.users u where u.id = p_user_id;
  return query
    select 'CONTA'::text, 'ultimo login'::text,
           coalesce(u.last_sign_in_at::date::text, 'nunca entrou')
      from auth.users u where u.id = p_user_id;
  return query
    select 'CONTA'::text, 'e admin do SaaS'::text,
           case when exists (select 1 from public.admins a where a.user_id = p_user_id)
                then 'sim' else 'nao' end::text;
  return query
    select 'CONTA'::text, 'organizacao'::text, 'nenhuma'::text;

  for r in
    select c.table_name
      from information_schema.columns c
      join information_schema.tables t
        on t.table_schema = c.table_schema and t.table_name = c.table_name
     where c.table_schema = 'public'
       and c.column_name = 'nutri_id'
       and t.table_type = 'BASE TABLE'
     order by c.table_name
  loop
    execute format('select count(*) from public.%I where nutri_id = $1', r.table_name)
      into v_qtd using p_user_id;
    v_tabelas := v_tabelas + 1;
    if v_qtd > 0 then
      v_com := v_com + 1;
      return query select 'DADOS'::text, r.table_name::text, v_qtd::text;
    end if;
  end loop;

  -- A linha de fechamento e o §23 em uma frase: sem ela, uma lista curta se
  -- leria como "quase nao ha dado", quando pode ser "quase nao ha tabela".
  return query
    select 'DADOS'::text,
           '(' || v_tabelas || ' tabelas conferidas)'::text,
           case when v_com = 0 then 'nenhuma com dado desta conta'
                else v_com || ' com dado' end::text;

  return query
    select 'STORAGE'::text, 'objetos'::text,
           (select count(*)::text from storage.objects so
             where (storage.foldername(so.name))[1] = p_user_id::text);
end $fn$;


