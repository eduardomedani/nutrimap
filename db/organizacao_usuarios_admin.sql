-- ===========================================================================
-- 1) CONVITES
-- ---------------------------------------------------------------------------
-- POR QUE TABELA PROPRIA, E NAO UMA LINHA "PENDENTE" EM organizacao_usuarios.
-- Um convite nao e um usuario. Ele expira, e revogavel, e de uso unico e tem
-- autor — nada disso pertence a quem TEM acesso. Separando, a pergunta "quem
-- entra na minha organizacao?" continua com uma resposta so, e o convite nao
-- precisa de auth_user_id nulo nem de um terceiro status.
--
-- O codigo NAO reaproveita nenhum dos tres que ja existem no projeto:
--   pacientes.codigo         abre a anamnese publica
--   funcionarios.codigo_acesso  vincula colaborador ao app da equipe
--   codigos_convite.codigo   cria organizacao nova (nivel SaaS)
-- Significados diferentes; misturar seria dar a um o poder do outro.
-- ===========================================================================

create table if not exists public.organizacao_convites (
  id             uuid primary key default gen_random_uuid(),
  organizacao_id uuid not null references public.organizacoes(id) on delete cascade,
  nome           text not null,
  email          text not null,
  perfil_id      uuid not null references public.perfis(id) on delete restrict,
  funcionario_id uuid references public.funcionarios(id) on delete set null,
  codigo         text not null,
  expira_em      timestamptz not null default now() + interval '14 days',
  revogado_em    timestamptz,
  usado_em       timestamptz,
  usado_por      uuid references auth.users(id) on delete set null,
  criado_por     uuid default auth.uid() references auth.users(id) on delete set null,
  criado_em      timestamptz not null default now()
);

-- Unico GLOBAL e por upper(): o vinculo procura o codigo sem saber de que
-- organizacao ele e, entao dois iguais em organizacoes diferentes tornariam a
-- busca ambigua.
create unique index if not exists uq_org_convite_codigo
  on public.organizacao_convites (upper(codigo));

create index if not exists idx_org_convite_org
  on public.organizacao_convites (organizacao_id, criado_em desc);

-- Um convite ABERTO por e-mail e organizacao. Convite usado ou revogado sai da
-- conta — reconvidar depois de revogar tem que funcionar.
create unique index if not exists uq_org_convite_email_aberto
  on public.organizacao_convites (organizacao_id, lower(email))
  where usado_em is null and revogado_em is null;


-- ===========================================================================
-- 2) AUDITORIA DA ADMINISTRACAO DE USUARIOS
-- ---------------------------------------------------------------------------
-- Segue a convencao das quatro auditorias que ja existem: DONO e AUTOR em
-- colunas separadas. Aqui a distincao finalmente tem valor pratico — ate agora
-- as duas guardavam a mesma pessoa.
-- ===========================================================================

create table if not exists public.organizacao_auditoria (
  id             bigint generated by default as identity primary key,
  organizacao_id uuid not null references public.organizacoes(id) on delete cascade,
  usuario_alvo   uuid,
  usuario_autor  uuid not null default auth.uid(),
  acao           text not null,
  antes          jsonb,
  depois         jsonb,
  criado_em      timestamptz not null default now()
);

alter table public.organizacao_auditoria drop constraint if exists organizacao_auditoria_acao_check;
alter table public.organizacao_auditoria add  constraint organizacao_auditoria_acao_check
  check (acao in ('codigo_gerado', 'codigo_revogado', 'vinculo_realizado',
                  'perfil_alterado', 'permissao_alterada',
                  'usuario_bloqueado', 'usuario_reativado'));

create index if not exists idx_org_auditoria
  on public.organizacao_auditoria (organizacao_id, criado_em desc);


-- ===========================================================================
-- 3) GERADOR DE CODIGO
-- ---------------------------------------------------------------------------
-- SECURITY DEFINER de proposito, e a licao vem do proprio projeto:
-- gerar_codigo_paciente() e INVOKER e so enxerga os proprios pacientes ao
-- testar unicidade, enquanto o codigo e unico GLOBAL. Com duas organizacoes,
-- ela gera codigo repetido. Aqui a funcao ve a tabela inteira.
--
-- Alfabeto sem 0/O/1/I/L: o codigo vai ser ditado por telefone e digitado a mao.
-- ===========================================================================

create or replace function public.gerar_codigo_organizacao()
returns text
language plpgsql
volatile
security definer
set search_path = public
as $fn$
declare
  alfabeto   text := 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
  v_codigo   text;
  i          integer;
  tentativas integer := 0;
begin
  loop
    v_codigo := 'EVL-';
    for i in 1..5 loop
      v_codigo := v_codigo || substr(alfabeto, 1 + floor(random() * length(alfabeto))::int, 1);
    end loop;

    if not exists (select 1 from public.organizacao_convites where upper(codigo) = v_codigo) then
      return v_codigo;
    end if;

    tentativas := tentativas + 1;
    if tentativas > 20 then
      raise exception 'nao_foi_possivel_gerar_codigo';
    end if;
  end loop;
end $fn$;


-- ===========================================================================
-- 4) TRAVA DO ULTIMO PROPRIETARIO
-- ---------------------------------------------------------------------------
-- NO BANCO, e nao so nas RPCs. E o que atende ao "mesmo que a UI tenha bug":
-- qualquer caminho — RPC, SQL Editor, script futuro — esbarra aqui.
--
-- Permite transferir a propriedade: promover outra pessoa a proprietario e,
-- so depois, rebaixar a primeira. O que ela impede e a organizacao ficar sem
-- nenhum proprietario ATIVO.
-- ===========================================================================

create or replace function public.fn_protege_ultimo_proprietario()
returns trigger
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_era_prop  boolean;
  v_sera_prop boolean;
  v_restantes integer;
begin
  select exists (select 1 from public.perfis p
                  where p.id = old.perfil_id and p.chave = 'proprietario')
    into v_era_prop;

  -- Linha que nao era proprietario ativo nao pode deixar a organizacao sem um.
  if not v_era_prop or old.status <> 'ativo' then
    if tg_op = 'DELETE' then return old; else return new; end if;
  end if;

  if tg_op = 'UPDATE' then
    select exists (select 1 from public.perfis p
                    where p.id = new.perfil_id and p.chave = 'proprietario')
      into v_sera_prop;
    -- Continua proprietario ativo: nada mudou do ponto de vista da trava.
    if v_sera_prop and new.status = 'ativo' then
      return new;
    end if;
  end if;

  select count(*) into v_restantes
    from public.organizacao_usuarios ou
    join public.perfis p on p.id = ou.perfil_id
   where ou.organizacao_id = old.organizacao_id
     and p.chave = 'proprietario'
     and ou.status = 'ativo'
     and ou.id <> old.id;

  if v_restantes = 0 then
    raise exception 'ultimo_proprietario';
  end if;

  if tg_op = 'DELETE' then return old; else return new; end if;
end $fn$;

drop trigger if exists trg_protege_ultimo_proprietario on public.organizacao_usuarios;
create trigger trg_protege_ultimo_proprietario
  before update or delete on public.organizacao_usuarios
  for each row execute function public.fn_protege_ultimo_proprietario();


