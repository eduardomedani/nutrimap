-- Guarda comum: devolve a organizacao do autor, ou estoura.
create or replace function public.exige_permissao(p_chave text)
returns uuid
language plpgsql
stable
security definer
set search_path = public
as $fn$
declare
  v_org uuid;
begin
  if auth.uid() is null then
    raise exception 'precisa_estar_logado';
  end if;
  v_org := public.organizacao_do_auth();
  if v_org is null then
    raise exception 'sem_organizacao';
  end if;
  if not public.tem_permissao(p_chave) then
    raise exception 'sem_permissao';
  end if;
  return v_org;
end $fn$;


create or replace function public.usuario_convidar(
  p_nome           text,
  p_email          text,
  p_perfil_chave   text,
  p_funcionario_id uuid default null
)
returns text
language plpgsql
volatile
security definer
set search_path = public
as $fn$
declare
  v_org    uuid;
  v_perfil uuid;
  v_codigo text;
  v_id     uuid;
begin
  v_org := public.exige_permissao('usuarios.gerenciar');

  if coalesce(btrim(p_nome), '') = '' or coalesce(btrim(p_email), '') = '' then
    raise exception 'nome_e_email_obrigatorios';
  end if;

  -- Proprietario NAO nasce por convite. Elevar alguem a proprietario e acao
  -- administrativa separada, e vai precisar de outra trava.
  if p_perfil_chave = 'proprietario' then
    raise exception 'perfil_proprietario_nao_permitido';
  end if;

  select id into v_perfil
    from public.perfis
   where chave = p_perfil_chave
     and ativo
     and (organizacao_id is null or organizacao_id = v_org);
  if v_perfil is null then
    raise exception 'perfil_invalido';
  end if;

  -- O funcionario, se informado, tem que ser da mesma organizacao. Sem isto,
  -- daria para amarrar um usuario ao colaborador de outra empresa.
  if p_funcionario_id is not null
     and not exists (select 1 from public.funcionarios f
                      where f.id = p_funcionario_id and f.nutri_id = v_org) then
    raise exception 'funcionario_de_outra_organizacao';
  end if;

  if exists (select 1 from public.organizacao_usuarios ou
              join auth.users u on u.id = ou.auth_user_id
             where ou.organizacao_id = v_org and lower(u.email) = lower(btrim(p_email))) then
    raise exception 'email_ja_e_membro';
  end if;

  v_codigo := public.gerar_codigo_organizacao();

  insert into public.organizacao_convites
    (organizacao_id, nome, email, perfil_id, funcionario_id, codigo)
  values
    (v_org, btrim(p_nome), lower(btrim(p_email)), v_perfil, p_funcionario_id, v_codigo)
  returning id into v_id;

  insert into public.organizacao_auditoria (organizacao_id, usuario_alvo, acao, depois)
  values (v_org, v_id, 'codigo_gerado',
          jsonb_build_object('nome', btrim(p_nome), 'email', lower(btrim(p_email)),
                             'perfil', p_perfil_chave));

  return v_codigo;
end $fn$;


create or replace function public.usuario_vincular(p_codigo text)
returns uuid
language plpgsql
volatile
security definer
set search_path = public
as $fn$
declare
  c        public.organizacao_convites%rowtype;
  v_email  text;
  v_id     uuid;
begin
  if auth.uid() is null then
    raise exception 'precisa_estar_logado';
  end if;

  if exists (select 1 from public.organizacao_usuarios where auth_user_id = auth.uid()) then
    raise exception 'conta_ja_vinculada';
  end if;

  select * into c from public.organizacao_convites
   where upper(codigo) = upper(btrim(p_codigo));

  if c.id is null                    then raise exception 'codigo_invalido'; end if;
  if c.revogado_em is not null       then raise exception 'codigo_revogado'; end if;
  if c.usado_em is not null          then raise exception 'codigo_usado';    end if;
  if c.expira_em < now()             then raise exception 'codigo_expirado'; end if;

  if not exists (select 1 from public.organizacoes o
                  where o.id = c.organizacao_id and o.ativo) then
    raise exception 'organizacao_inativa';
  end if;

  -- E-MAIL COMPATIVEL. Sem isto o codigo sozinho e a credencial: quem o
  -- interceptar entra na organizacao. Com isto ele so vale para quem foi
  -- convidado, e um codigo vazado nao serve para mais ninguem.
  select lower(u.email) into v_email from auth.users u where u.id = auth.uid();
  if v_email is distinct from lower(c.email) then
    raise exception 'email_diferente_do_convite';
  end if;

  insert into public.organizacao_usuarios
    (organizacao_id, auth_user_id, nome, perfil_id, funcionario_id, status)
  values
    (c.organizacao_id, auth.uid(), c.nome, c.perfil_id, c.funcionario_id, 'ativo')
  returning id into v_id;

  update public.organizacao_convites
     set usado_em = now(), usado_por = auth.uid()
   where id = c.id;

  insert into public.organizacao_auditoria (organizacao_id, usuario_alvo, acao, depois)
  values (c.organizacao_id, v_id, 'vinculo_realizado',
          jsonb_build_object('email', v_email, 'convite', c.id));

  return v_id;
end $fn$;


create or replace function public.usuario_definir_perfil(p_usuario_id uuid, p_perfil_id uuid)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $fn$
declare
  v_org    uuid;
  v_antes  uuid;
  v_chave  text;
begin
  v_org := public.exige_permissao('usuarios.gerenciar');

  select perfil_id into v_antes
    from public.organizacao_usuarios
   where id = p_usuario_id and organizacao_id = v_org;
  if v_antes is null then
    raise exception 'usuario_nao_encontrado';
  end if;

  select chave into v_chave
    from public.perfis
   where id = p_perfil_id and ativo
     and (organizacao_id is null or organizacao_id = v_org);
  if v_chave is null then
    raise exception 'perfil_invalido';
  end if;
  if v_chave = 'proprietario' then
    raise exception 'perfil_proprietario_nao_permitido';
  end if;

  -- A trava do ultimo proprietario mora no trigger: se esta linha for o unico
  -- proprietario ativo, o update abaixo estoura com 'ultimo_proprietario'.
  update public.organizacao_usuarios
     set perfil_id = p_perfil_id
   where id = p_usuario_id and organizacao_id = v_org;

  insert into public.organizacao_auditoria (organizacao_id, usuario_alvo, acao, antes, depois)
  values (v_org, p_usuario_id, 'perfil_alterado',
          jsonb_build_object('perfil_id', v_antes),
          jsonb_build_object('perfil_id', p_perfil_id, 'chave', v_chave));
end $fn$;


create or replace function public.usuario_definir_status(p_usuario_id uuid, p_status text)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $fn$
declare
  v_org   uuid;
  v_antes text;
begin
  v_org := public.exige_permissao('usuarios.gerenciar');

  if p_status not in ('ativo', 'bloqueado') then
    raise exception 'status_invalido';
  end if;

  select status into v_antes
    from public.organizacao_usuarios
   where id = p_usuario_id and organizacao_id = v_org;
  if v_antes is null then
    raise exception 'usuario_nao_encontrado';
  end if;

  -- Ninguem se bloqueia. Sem isto, o unico administrador se tranca do lado de
  -- fora e ninguem mais consegue reativar.
  if p_status = 'bloqueado'
     and exists (select 1 from public.organizacao_usuarios
                  where id = p_usuario_id and auth_user_id = auth.uid()) then
    raise exception 'nao_pode_bloquear_a_si_mesmo';
  end if;

  update public.organizacao_usuarios
     set status = p_status
   where id = p_usuario_id and organizacao_id = v_org;

  insert into public.organizacao_auditoria (organizacao_id, usuario_alvo, acao, antes, depois)
  values (v_org, p_usuario_id,
          case when p_status = 'bloqueado' then 'usuario_bloqueado' else 'usuario_reativado' end,
          jsonb_build_object('status', v_antes),
          jsonb_build_object('status', p_status));
end $fn$;


-- p_modo: 'perfil' apaga a excecao | 'permitir' concede | 'bloquear' revoga.
-- Permissao herdada NAO vira linha: o padrao do perfil e a ausencia.
create or replace function public.usuario_definir_permissao(
  p_usuario_id uuid, p_chave text, p_modo text
)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $fn$
declare
  v_org   uuid;
  v_antes text;
begin
  v_org := public.exige_permissao('usuarios.gerenciar');

  if p_modo not in ('perfil', 'permitir', 'bloquear') then
    raise exception 'modo_invalido';
  end if;
  if not exists (select 1 from public.permissoes where chave = p_chave) then
    raise exception 'permissao_invalida';
  end if;
  if not exists (select 1 from public.organizacao_usuarios
                  where id = p_usuario_id and organizacao_id = v_org) then
    raise exception 'usuario_nao_encontrado';
  end if;

  select case when concede then 'permitir' else 'bloquear' end into v_antes
    from public.usuario_permissoes
   where usuario_id = p_usuario_id and permissao_chave = p_chave;

  if p_modo = 'perfil' then
    delete from public.usuario_permissoes
     where usuario_id = p_usuario_id and permissao_chave = p_chave;
  else
    insert into public.usuario_permissoes (usuario_id, permissao_chave, concede)
    values (p_usuario_id, p_chave, p_modo = 'permitir')
    on conflict (usuario_id, permissao_chave)
      do update set concede = excluded.concede;
  end if;

  insert into public.organizacao_auditoria (organizacao_id, usuario_alvo, acao, antes, depois)
  values (v_org, p_usuario_id, 'permissao_alterada',
          jsonb_build_object('chave', p_chave, 'modo', coalesce(v_antes, 'perfil')),
          jsonb_build_object('chave', p_chave, 'modo', p_modo));
end $fn$;


create or replace function public.usuario_convite_revogar(p_convite_id uuid)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $fn$
declare
  v_org uuid;
begin
  v_org := public.exige_permissao('usuarios.gerenciar');

  update public.organizacao_convites
     set revogado_em = now()
   where id = p_convite_id
     and organizacao_id = v_org
     and usado_em is null
     and revogado_em is null;

  if not found then
    raise exception 'convite_nao_encontrado';
  end if;

  insert into public.organizacao_auditoria (organizacao_id, usuario_alvo, acao)
  values (v_org, p_convite_id, 'codigo_revogado');
end $fn$;


-- ===========================================================================
-- 6) LEITURAS
-- ---------------------------------------------------------------------------
-- Sao RPC e nao `select` direto porque o E-MAIL mora em auth.users, que o
-- PostgREST nao expoe. Copiar o email para organizacao_usuarios criaria uma
-- segunda fonte que envelhece quando a pessoa troca de email no Auth.
-- ===========================================================================

create or replace function public.usuarios_da_organizacao()
returns table (
  id uuid, nome text, email text, perfil_chave text, perfil_nome text,
  status text, funcionario_nome text, ultimo_acesso_em timestamptz,
  e_proprietario boolean, sou_eu boolean, excecoes integer
)
language sql
stable
security definer
set search_path = public
as $fn$
  select
    ou.id, ou.nome, u.email, p.chave, p.nome,
    ou.status, f.nome, ou.ultimo_acesso_em,
    p.chave = 'proprietario',
    ou.auth_user_id = auth.uid(),
    (select count(*)::int from public.usuario_permissoes up where up.usuario_id = ou.id)
  from public.organizacao_usuarios ou
  join public.perfis p    on p.id = ou.perfil_id
  join auth.users u       on u.id = ou.auth_user_id
  left join public.funcionarios f on f.id = ou.funcionario_id
  where ou.organizacao_id = public.organizacao_do_auth()
    and public.tem_permissao('usuarios.visualizar')
  order by (p.chave = 'proprietario') desc, ou.nome;
$fn$;


create or replace function public.convites_pendentes()
returns table (
  id uuid, nome text, email text, perfil_nome text,
  codigo text, expira_em timestamptz, expirado boolean, criado_em timestamptz
)
language sql
stable
security definer
set search_path = public
as $fn$
  select c.id, c.nome, c.email, p.nome, c.codigo, c.expira_em,
         c.expira_em < now(), c.criado_em
  from public.organizacao_convites c
  join public.perfis p on p.id = c.perfil_id
  where c.organizacao_id = public.organizacao_do_auth()
    and c.usado_em is null
    and c.revogado_em is null
    and public.tem_permissao('usuarios.gerenciar')
  order by c.criado_em desc;
$fn$;


-- As permissoes de UM usuario, com a origem de cada uma. E o que a tela do §14
-- precisa para dizer "Herdado" ou "Personalizado" sem o administrador ter que
-- entender perfil_permissoes e usuario_permissoes.
create or replace function public.permissoes_do_usuario(p_usuario_id uuid)
returns table (
  chave text, modulo text, acao text, descricao text, sensivel boolean, ordem integer,
  do_perfil boolean, modo text, efetiva boolean
)
language sql
stable
security definer
set search_path = public
as $fn$
  select
    pm.chave, pm.modulo, pm.acao, pm.descricao, pm.sensivel, pm.ordem,
    pp.permissao_chave is not null,
    case when up.permissao_chave is null then 'perfil'
         when up.concede then 'permitir' else 'bloquear' end,
    coalesce(up.concede, pp.permissao_chave is not null)
  from public.permissoes pm
  cross join public.organizacao_usuarios ou
  left join public.perfil_permissoes pp
    on pp.perfil_id = ou.perfil_id and pp.permissao_chave = pm.chave
  left join public.usuario_permissoes up
    on up.usuario_id = ou.id and up.permissao_chave = pm.chave
  where ou.id = p_usuario_id
    and ou.organizacao_id = public.organizacao_do_auth()
    and public.tem_permissao('usuarios.visualizar')
  order by pm.ordem;
$fn$;


